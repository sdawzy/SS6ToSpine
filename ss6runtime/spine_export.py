def _quad_world_vertices(part, cell):
    """Return 4 world-space vertices matching the preview renderer's Y-up cell geometry."""
    M=part.get("world_affine")
    if not M:
        return None
    w=float(cell.get("width",0)); h=float(cell.get("height",0))
    piv=cell.get("pivot",{}) or {}
    px=float(piv.get("x",w/2)); py=float(piv.get("y",h/2))
    loc=[
        (-px, py),
        (w-px, py),
        (w-px, py-h),
        (-px, py-h),
    ]
    out=[]
    for x,y in loc:
        q=_apply(M,x,y)
        out.extend([round(q[0],6),round(q[1],6)])
    return out

def _part_world_geometry(part, cell, mesh_v_flip=False):
    """
    Return (vertices, uvs, triangles) in ROOT/world coordinates.

    All exported baked attachments live directly on the Spine root bone, so
    world coordinates from the Python runtime are also attachment-local coords.
    """
    mesh=part.get("skinned_mesh")
    if isinstance(mesh,dict) and mesh.get("vertices") and mesh.get("triangles"):
        verts=[]
        for v in mesh["vertices"]:
            verts.extend([round(float(v["x"]),6),round(float(v["y"]),6)])
        uvs=_uvs_from_ss6(mesh.get("uv",[]),mesh_v_flip)
        triangles=[int(x) for x in (mesh.get("triangles",[]) or [])]
        return verts,uvs,triangles

    verts=_quad_world_vertices(part,cell)
    if verts is None:
        return None,None,None
    # Region-local UVs for a full rectangular atlas region.
    if mesh_v_flip:
        uvs=[0.0,1.0, 1.0,1.0, 1.0,0.0, 0.0,0.0]
    else:
        uvs=[0.0,0.0, 1.0,0.0, 1.0,1.0, 0.0,1.0]
    triangles=[0,1,2, 2,3,0]
    return verts,uvs,triangles

def _trim_zero_deform(delta,tol=1e-7):
    """
    Spine deform supports offset + partial vertex arrays.
    Trim leading/trailing zero scalars to shrink JSON substantially.
    """
    first=None;last=None
    for i,v in enumerate(delta):
        if abs(float(v))>tol:
            first=i;break
    if first is None:
        return None,None
    for i in range(len(delta)-1,-1,-1):
        if abs(float(delta[i]))>tol:
            last=i;break
    return first,[round(float(x),6) for x in delta[first:last+1]]

def export_spine_baked(parts_raw_path,animation_raw_path,cellmap_path,texture_dir,
                       output_dir,setup_frame=0,name=None,mesh_v_flip=False,
                       show_hidden=False,stepped=False):
    """
    Fidelity-first exporter.

    Instead of exporting 100+ animated bones, every visible SS6 part is converted
    to an unweighted Spine mesh attached directly to root. Its final evaluated
    world vertices are then baked into a deform timeline.

    This bypasses Spine transform decomposition/interpolation completely.
    """
    out=Path(output_dir);out.mkdir(parents=True,exist_ok=True)
    rt=Runtime.from_files(parts_raw_path,animation_raw_path)
    frames=_eval_all_frames(rt)
    maps=_parse_maps(_load(cellmap_path))
    regions=_build_regions(maps)

    skeleton_name=_safe(name or Path(output_dir).name or "ss6_character")
    atlas_path=out/f"{skeleton_name}.atlas"
    _write_atlas(maps,texture_dir,out,atlas_path)

    # Stable visual-part list: any part that has a known cell in any frame.
    visual_indices=[]
    part_names={}
    used_cells={}
    for state in frames:
        for p in state["parts"]:
            idx=int(p["index"])
            key=_part_key_to_cell(p)
            if key is None or key not in regions:
                continue
            part_names[idx]=str(p["name"])
            if idx not in visual_indices:
                visual_indices.append(idx)
            used_cells.setdefault(idx,[])
            if key not in used_cells[idx]:
                used_cells[idx].append(key)

    # Setup draw order from selected setup frame.
    sf=frames[int(setup_frame)]
    sf_by_index={int(p["index"]):p for p in sf["parts"]}
    ordered=[]
    for idx in visual_indices:
        p=sf_by_index.get(idx)
        if p:
            ordered.append((int(p.get("priority",0) or 0),idx))
        else:
            ordered.append((0,idx))
    ordered.sort()
    visual_indices=[idx for _,idx in ordered]

    bones=[{"name":"root"}]
    slots=[]
    attachments={}
    meta={}
    warnings=[]

    # Build every cell attachment using the FIRST frame in which that cell is active.
    for idx in visual_indices:
        slot=part_names[idx]
        attachments[slot]={}
        attach_names={}

        setup_part=sf_by_index.get(idx)
        setup_key=_part_key_to_cell(setup_part) if setup_part else None
        setup_attachment=None

        for cell_key in used_cells.get(idx,[]):
            region_name,cell,_=regions[cell_key]
            source_part=None
            source_frame=None
            for fi,state in enumerate(frames):
                byidx={int(p["index"]):p for p in state["parts"]}
                p=byidx.get(idx)
                if p and _part_key_to_cell(p)==cell_key:
                    source_part=p;source_frame=fi;break
            if source_part is None:
                continue

            verts,uvs,tris=_part_world_geometry(source_part,cell,mesh_v_flip=mesh_v_flip)
            if not verts:
                warnings.append(f"{slot}: could not build geometry for cell {cell_key}")
                continue

            aname=slot if cell_key==setup_key else f"{slot}__{region_name}"
            attachments[slot][aname]={
                "type":"mesh",
                "path":region_name,
                "uvs":uvs,
                "triangles":tris,
                "vertices":verts,
                "hull":len(verts)//2,
                "width":float(cell.get("width",0)),
                "height":float(cell.get("height",0)),
            }
            attach_names[cell_key]=aname
            if cell_key==setup_key:
                setup_attachment=aname

        # If setup frame has no active cell, use first known attachment but hide slot.
        if setup_attachment is None and attach_names:
            setup_attachment=next(iter(attach_names.values()))

        s={"name":slot,"bone":"root"}
        if setup_attachment is not None:
            s["attachment"]=setup_attachment

        visible=False
        alpha=1.0
        if setup_part:
            visible=_part_visible(setup_part,regions,show_hidden=show_hidden)
            alpha=float(setup_part.get("opacity",1.0) if isinstance(setup_part.get("opacity",1.0),(int,float)) else 1.0)
        if not visible:
            alpha=0.0
        if alpha<0.9999:
            s["color"]=_rgba_hex(alpha)
        slots.append(s)

        meta[slot]={
            "part_index":idx,
            "attachment_names":attach_names,
            "setup_attachment":setup_attachment,
        }

    # Build animation.
    anim_name=str(frames[0].get("animation") or "animation")
    fps=float(max(rt.fps,1.0))
    deform_skin={}
    slot_tl={}
    draworder=[]
    deform_keys=0

    prev_slot={}
    prev_order=[s["name"] for s in slots]

    # Cache attachment setup vertices.
    setup_vertices={}
    for slot,atts in attachments.items():
        for an,att in atts.items():
            setup_vertices[(slot,an)]=att.get("vertices",[]) or []

    for fi,state in enumerate(frames):
        t=_frame_time(fi,fps)
        byidx={int(p["index"]):p for p in state["parts"]}
        order_rows=[]

        for slot,m in meta.items():
            idx=int(m["part_index"])
            p=byidx.get(idx)
            if not p:
                continue
            cell_key=_part_key_to_cell(p)
            aname=m["attachment_names"].get(cell_key)
            visible=_part_visible(p,regions,show_hidden=show_hidden) and aname is not None
            alpha=float(p.get("opacity",1.0) if isinstance(p.get("opacity",1.0),(int,float)) else 1.0) if visible else 0.0
            color=_rgba_hex(alpha)

            # Attachment/color timelines.
            old=prev_slot.get(slot,{
                "attachment":m["setup_attachment"],
                "color":next((s.get("color","ffffffff") for s in slots if s["name"]==slot),"ffffffff")
            })
            cur={"attachment":aname if aname is not None else old["attachment"],"color":color}
            if old["attachment"]!=cur["attachment"]:
                slot_tl.setdefault(slot,{}).setdefault("attachment",[]).append({"time":t,"name":cur["attachment"]})
            if old["color"]!=cur["color"]:
                k={"time":t,"color":cur["color"]}
                if stepped:k["curve"]="stepped"
                slot_tl.setdefault(slot,{}).setdefault("color",[]).append(k)
            prev_slot[slot]=cur

            # Deform only active attachment.
            if visible and aname is not None:
                region_name,cell,_=regions[cell_key]
                verts,uvs,tris=_part_world_geometry(p,cell,mesh_v_flip=mesh_v_flip)
                base=setup_vertices.get((slot,aname),[])
                if verts and len(verts)==len(base):
                    delta=[float(v)-float(b) for v,b in zip(verts,base)]
                    offset,trimmed=_trim_zero_deform(delta)
                    key={"time":t}
                    if trimmed is not None:
                        if offset:
                            key["offset"]=int(offset)
                        key["vertices"]=trimmed
                    if stepped:
                        key["curve"]="stepped"
                    deform_skin.setdefault(slot,{}).setdefault(aname,[]).append(key)
                    deform_keys+=1

            order_rows.append((int(p.get("priority",0) or 0),idx,slot))

        cur_order=[s for _,_,s in sorted(order_rows)]
        if fi>0 and cur_order and cur_order!=prev_order:
            offsets=[]
            for ci,slot in enumerate(cur_order):
                if slot in prev_order:
                    si=prev_order.index(slot)
                    off=ci-si
                    if off!=0:offsets.append({"slot":slot,"offset":off})
            if offsets:
                draworder.append({"time":t,"offsets":offsets})
            prev_order=cur_order

    anim={}
    if slot_tl:anim["slots"]=slot_tl
    if deform_skin:anim["deform"]={"default":deform_skin}
    if draworder:anim["draworder"]=draworder
    # Ensure importer always sees an animation even in degenerate cases.
    if not anim:
        anim={"bones":{"root":{"rotate":[{"time":0.0,"angle":0.0}]}}}

    doc={
        "skeleton":{
            "spine":"4.2.00",
            "images":"./textures/",
            "ss6Runtime":"ss6python_runtime_v22",
            "ss6Animation":anim_name,
            "ss6Frame":int(setup_frame),
            "ss6Mode":"baked-world-mesh-deform"
        },
        "bones":bones,
        "slots":slots,
        "skins":[{"name":"default","attachments":attachments}],
        "animations":{
            "setup":{"bones":{"root":{"rotate":[{"time":0.0,"angle":0.0}]}}},
            anim_name:anim
        }
    }

    json_path=out/f"{skeleton_name}.json"
    json_path.write_text(json.dumps(doc,ensure_ascii=False,indent=2),encoding="utf-8")

    timeline_count=0
    for slot,v in deform_skin.items():
        timeline_count+=len(v)
    slot_timeline_count=sum(len(v) for v in slot_tl.values())

    report={
        "json":str(json_path),
        "atlas":str(atlas_path),
        "animation":anim_name,
        "setup_frame":int(setup_frame),
        "frame_count":int(rt.frame_count),
        "fps":float(rt.fps),
        "export_mode":"baked-world-mesh-deform",
        "bones":len(bones),
        "slots":len(slots),
        "deform_timelines":timeline_count,
        "deform_keyframes":deform_keys,
        "slot_timelines":slot_timeline_count,
        "draworder_keyframes":len(draworder),
        "stepped":bool(stepped),
        "warnings":warnings,
    }
    (out/"spine_export_report.json").write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding="utf-8")
    return report

