def _quantize_float(v, tol):
    if tol is None or tol <= 0:
        return round(float(v), 9)
    return int(round(float(v) / float(tol)))

def _optimized_geom_signature(cell_key, verts, uvs, tris, tolerance=1e-4):
    """
    Approximate geometry signature.

    - region/cell must match exactly
    - triangle topology must match exactly
    - UVs are quantized tightly
    - vertex coordinates are quantized using user tolerance

    tolerance=0 means effectively exact (9 decimal places).
    """
    return (
        tuple(cell_key),
        tuple(_quantize_float(x, tolerance) for x in verts),
        tuple(_quantize_float(x, 1e-7) for x in uvs),
        tuple(int(x) for x in tris),
    )

def _sample_indices(frame_count, source_fps, export_fps=None, frame_step=None):
    """
    Select source sample indices while preserving original animation time.

    frame_step takes precedence over export_fps.
    The final source frame is included if not already selected.
    """
    n=int(frame_count)
    if n<=0:
        return []

    if frame_step is not None:
        step=max(1,int(frame_step))
        idx=list(range(0,n,step))
    elif export_fps is not None and float(export_fps)>0 and float(export_fps)<float(source_fps)-1e-9:
        target=float(export_fps)
        duration=(n-1)/float(source_fps)
        # Sample target-clock times and map to nearest source frame.
        count=int(math.floor(duration*target+1e-9))+1
        idx=[]
        for k in range(count):
            t=k/target
            fi=int(round(t*float(source_fps)))
            fi=max(0,min(n-1,fi))
            if not idx or idx[-1]!=fi:
                idx.append(fi)
    else:
        idx=list(range(n))

    if idx[-1] != n-1:
        idx.append(n-1)
    return idx

def _visible_order_signature(state, visual_indices, part_names, regions, show_hidden=False):
    rows=[]
    allowed=set(int(x) for x in visual_indices)
    for p in state["parts"]:
        idx=int(p["index"])
        if idx not in allowed:
            continue
        if not _part_visible(p,regions,show_hidden=show_hidden):
            continue
        rows.append((int(p.get("priority",0) or 0),idx,part_names[idx]))
    return tuple(s for _,_,s in sorted(rows))

def _full_order(state, visual_indices, part_names):
    allowed=set(int(x) for x in visual_indices)
    rows=[]
    for p in state["parts"]:
        idx=int(p["index"])
        if idx not in allowed:
            continue
        rows.append((int(p.get("priority",0) or 0),idx,part_names[idx]))
    return [s for _,_,s in sorted(rows)]

def export_spine_frame_swap_all(parts_raw_path, animation_entries, cellmap_path, texture_dir,
                                output_dir, setup_animation_name=None, setup_frame=0,
                                name=None, mesh_v_flip=False, show_hidden=False,
                                dedupe=True, dedupe_tolerance=1e-4,
                                export_fps=None, frame_step=None):
    """
    v0.24 optimized combined frame-swap exporter.

    Fidelity model is unchanged from v0.22:
      - one root bone
      - baked mesh attachment per sampled visual state
      - stepped attachment switching

    Optimizations:
      - approximate cross-frame/cross-animation dedupe
      - sparse opacity timelines
      - draw-order changes only when visible ordering changes
      - optional downsampling
    """
    out=Path(output_dir)
    out.mkdir(parents=True,exist_ok=True)

    maps=_parse_maps(_load(cellmap_path))
    regions=_build_regions(maps)

    runtime_set=_load_runtime_set(parts_raw_path,animation_entries)
    if not runtime_set:
        raise RuntimeError("No animations selected for export.")

    setup_idx=_select_setup_animation(runtime_set,setup_animation_name)
    setup_entry,setup_rt,setup_frames=runtime_set[setup_idx]
    if setup_frame<0 or setup_frame>=len(setup_frames):
        raise RuntimeError(
            f"setup_frame {setup_frame} out of range for {setup_entry['name']} "
            f"(frames={len(setup_frames)})"
        )

    skeleton_name=_safe(name or Path(output_dir).name or "ss6_character")
    atlas_path=out/f"{skeleton_name}.atlas"
    _write_atlas(maps,texture_dir,out,atlas_path)

    # Union of visual parts over all original frames.
    visual_indices=[]
    part_names={}
    for e,rt,frames in runtime_set:
        for state in frames:
            for p in state["parts"]:
                idx=int(p["index"])
                key=_part_key_to_cell(p)
                if key is None or key not in regions:
                    continue
                part_names[idx]=str(p["name"])
                if idx not in visual_indices:
                    visual_indices.append(idx)

    setup_state=setup_frames[int(setup_frame)]
    setup_byidx={int(p["index"]):p for p in setup_state["parts"]}
    visual_indices.sort(key=lambda idx:(
        int(setup_byidx.get(idx,{}).get("priority",0) or 0),
        idx
    ))

    bones=[{"name":"root"}]
    slots=[]
    skin_attachments={part_names[idx]:{} for idx in visual_indices}
    warnings=[]

    # One cache per slot, shared across ALL animations.
    global_geom_cache={idx:{} for idx in visual_indices}
    frame_attachment={}  # (anim_name, part_idx, source_frame) -> attachment name
    total_attachments=0
    dedupe_hits=0

    # Per-animation sample plans.
    sample_plan={}
    for e,rt,frames in runtime_set:
        sample_plan[str(e["name"])]=_sample_indices(
            len(frames),rt.fps,export_fps=export_fps,frame_step=frame_step
        )

    # Build baked attachments only for selected sample frames.
    for e,rt,frames in runtime_set:
        anim_name=str(e["name"])
        anim_safe=_safe(anim_name)
        for source_fi in sample_plan[anim_name]:
            state=frames[source_fi]
            byidx={int(p["index"]):p for p in state["parts"]}

            for idx in visual_indices:
                p=byidx.get(idx)
                if p is None:
                    frame_attachment[(anim_name,idx,source_fi)]=None
                    continue

                cell_key=_part_key_to_cell(p)
                visible=_part_visible(p,regions,show_hidden=show_hidden)
                if cell_key is None or cell_key not in regions or not visible:
                    frame_attachment[(anim_name,idx,source_fi)]=None
                    continue

                region_name,cell,_=regions[cell_key]
                verts,uvs,tris=_part_world_geometry(p,cell,mesh_v_flip=mesh_v_flip)
                if not verts:
                    warnings.append(f"{anim_name}/{part_names[idx]}: frame {source_fi} geometry missing")
                    frame_attachment[(anim_name,idx,source_fi)]=None
                    continue

                sig=None
                if dedupe:
                    sig=_optimized_geom_signature(
                        cell_key,verts,uvs,tris,tolerance=dedupe_tolerance
                    )

                cache=global_geom_cache[idx]
                if sig is not None and sig in cache:
                    aname=cache[sig]
                    dedupe_hits+=1
                else:
                    slot_name=part_names[idx]
                    aname=f"{slot_name}__{anim_safe}__f{source_fi:03d}"
                    base=aname
                    suffix=1
                    while aname in skin_attachments[slot_name]:
                        aname=f"{base}_{suffix}"
                        suffix+=1

                    skin_attachments[slot_name][aname]={
                        "type":"mesh",
                        "path":region_name,
                        "uvs":uvs,
                        "triangles":tris,
                        "vertices":verts,
                        "hull":len(verts)//2,
                        "width":float(cell.get("width",0)),
                        "height":float(cell.get("height",0)),
                    }
                    total_attachments+=1
                    if sig is not None:
                        cache[sig]=aname

                frame_attachment[(anim_name,idx,source_fi)]=aname

    # Setup slots from chosen setup animation/frame.
    setup_anim_name=str(setup_entry["name"])
    for idx in visual_indices:
        slot_name=part_names[idx]

        setup_attachment=frame_attachment.get((setup_anim_name,idx,int(setup_frame)))
        if setup_attachment is None:
            # Find any exported attachment so the slot is structurally valid.
            found=None
            for e,rt,frames in runtime_set:
                an=str(e["name"])
                for fi in sample_plan[an]:
                    q=frame_attachment.get((an,idx,fi))
                    if q is not None:
                        found=q;break
                if found is not None:
                    break
            setup_attachment=found

        s={"name":slot_name,"bone":"root"}
        if setup_attachment is not None:
            s["attachment"]=setup_attachment

        p0=setup_byidx.get(idx)
        visible0=False
        alpha0=1.0
        if p0 is not None:
            visible0=_part_visible(p0,regions,show_hidden=show_hidden)
            alpha0=float(
                p0.get("opacity",1.0)
                if isinstance(p0.get("opacity",1.0),(int,float))
                else 1.0
            )
        if not visible0:
            alpha0=0.0
        if alpha0<0.9999:
            s["color"]=_rgba_hex(alpha0)
        slots.append(s)

    setup_order=[s["name"] for s in slots]

    animations={
        "setup":{"bones":{"root":{"rotate":[{"time":0.0,"angle":0.0}]}}}
    }
    animation_reports=[]

    for e,rt,frames in runtime_set:
        anim_name=str(e["name"])
        fps=float(max(rt.fps,1.0))
        indices=sample_plan[anim_name]
        slot_timelines={}
        draworder=[]

        # Attachment timelines.
        for idx in visual_indices:
            slot_name=part_names[idx]
            attachment_keys=[]
            prev_att=object()

            for source_fi in indices:
                t=_frame_time(source_fi,fps)
                aname=frame_attachment.get((anim_name,idx,source_fi))
                if aname!=prev_att:
                    k={"time":t,"curve":"stepped"}
                    if aname is not None:
                        k["name"]=aname
                    attachment_keys.append(k)
                    prev_att=aname

            if attachment_keys:
                slot_timelines.setdefault(slot_name,{})["attachment"]=attachment_keys

        # Sparse opacity timelines:
        # Hidden frames are handled by attachment=null, so do NOT emit color=0
        # just because a part is hidden. Only real visible opacity changes matter.
        for idx in visual_indices:
            slot_name=part_names[idx]
            color_keys=[]
            prev_alpha=None
            any_nonopaque=False

            for source_fi in indices:
                state=frames[source_fi]
                byidx={int(p["index"]):p for p in state["parts"]}
                p=byidx.get(idx)
                if p is None:
                    continue
                visible=_part_visible(p,regions,show_hidden=show_hidden)
                if not visible:
                    continue

                alpha=float(
                    p.get("opacity",1.0)
                    if isinstance(p.get("opacity",1.0),(int,float))
                    else 1.0
                )
                if abs(alpha-1.0)>1e-6:
                    any_nonopaque=True

                if prev_alpha is None or abs(alpha-prev_alpha)>1e-6:
                    color_keys.append({
                        "time":_frame_time(source_fi,fps),
                        "color":_rgba_hex(alpha),
                        "curve":"stepped"
                    })
                    prev_alpha=alpha

            # Entirely opaque visible samples => no color timeline at all.
            if any_nonopaque and color_keys:
                slot_timelines.setdefault(slot_name,{})["color"]=color_keys

        # Draw order:
        # ignore changes caused only by hidden slots.
        prev_visible_sig=None
        prev_full_order=setup_order
        for source_fi in indices:
            state=frames[source_fi]
            visible_sig=_visible_order_signature(
                state,visual_indices,part_names,regions,show_hidden=show_hidden
            )
            full_order=_full_order(state,visual_indices,part_names)

            if prev_visible_sig is None:
                prev_visible_sig=visible_sig
                prev_full_order=full_order
                continue

            if visible_sig != prev_visible_sig:
                offsets=[]
                for ci,slot_name in enumerate(full_order):
                    if slot_name not in setup_order:
                        continue
                    si=setup_order.index(slot_name)
                    off=ci-si
                    if off!=0:
                        offsets.append({"slot":slot_name,"offset":off})
                if offsets:
                    draworder.append({
                        "time":_frame_time(source_fi,fps),
                        "offsets":offsets
                    })
                prev_visible_sig=visible_sig
                prev_full_order=full_order

        end_time=_end_time(len(frames),fps)
        anim={
            "bones":{
                "root":{
                    "rotate":[
                        {"time":0.0,"angle":0.0},
                        {"time":end_time,"angle":0.0}
                    ]
                }
            },
            "slots":slot_timelines
        }
        if draworder:
            anim["draworder"]=draworder
        animations[anim_name]=anim

        attachment_timeline_count=sum(
            1 for v in slot_timelines.values() if "attachment" in v
        )
        attachment_keyframes=sum(
            len(v.get("attachment",[])) for v in slot_timelines.values()
        )
        color_timeline_count=sum(
            1 for v in slot_timelines.values() if "color" in v
        )
        color_keyframes=sum(
            len(v.get("color",[])) for v in slot_timelines.values()
        )

        effective_fps = (
            float(export_fps)
            if export_fps is not None and float(export_fps)>0 and float(export_fps)<fps
            else (fps/max(1,int(frame_step)) if frame_step else fps)
        )

        animation_reports.append({
            "name":anim_name,
            "source_frame_count":int(rt.frame_count),
            "source_fps":float(rt.fps),
            "exported_samples":len(indices),
            "effective_export_fps":round(effective_fps,6),
            "sample_indices":indices,
            "duration":_end_time(int(rt.frame_count),rt.fps),
            "terminal_hold":True,
            "attachment_timelines":attachment_timeline_count,
            "attachment_keyframes":attachment_keyframes,
            "color_timelines":color_timeline_count,
            "color_keyframes":color_keyframes,
            "draworder_keyframes":len(draworder),
        })

    doc={
        "skeleton":{
            "spine":"4.2.00",
            "images":"./textures/",
            "ss6Runtime":"ss6python_runtime_v24",
            "ss6Mode":"frame-swap-all-animations-optimized",
            "ss6SetupAnimation":setup_anim_name,
            "ss6SetupFrame":int(setup_frame)
        },
        "bones":bones,
        "slots":slots,
        "skins":[{"name":"default","attachments":skin_attachments}],
        "animations":animations
    }

    json_path=out/f"{skeleton_name}.json"
    json_path.write_text(json.dumps(doc,ensure_ascii=False,separators=(",",":")),encoding="utf-8")

    # Also provide a human-readable report.
    report={
        "json":str(json_path),
        "atlas":str(atlas_path),
        "export_mode":"frame-swap-all-animations-optimized",
        "setup_animation":setup_anim_name,
        "setup_frame":int(setup_frame),
        "animations_exported":len(runtime_set),
        "animation_names":[str(e["name"]) for e,_,_ in runtime_set],
        "bones":1,
        "slots":len(slots),
        "mesh_attachments":total_attachments,
        "dedupe":bool(dedupe),
        "dedupe_tolerance":float(dedupe_tolerance),
        "dedupe_hits":dedupe_hits,
        "export_fps":export_fps,
        "frame_step":frame_step,
        "animations":animation_reports,
        "warnings":warnings,
    }
    (out/"spine_export_report.json").write_text(
        json.dumps(report,ensure_ascii=False,indent=2),
        encoding="utf-8"
    )
    return report

