def _safe(s):
    s = re.sub(r'[<>:"/\\|?*]+', "_", str(s))
    return s.strip(" .") or "unnamed"

def _frame_time(frame_index, fps):
    """High-precision frame timestamp for exact sampled playback."""
    return round(float(frame_index) / float(max(fps, 1.0)), 9)

def _end_time(frame_count, fps):
    """Animation end after the final sampled frame has displayed for one frame."""
    return round(float(frame_count) / float(max(fps, 1.0)), 9)

def _norm_angle(a):
    a = (float(a) + 180.0) % 360.0 - 180.0
    if abs(a) < 1e-8:
        a = 0.0
    return a


def _affine_to_components(M):
    """
    Exact 2D affine -> Spine-compatible rotation/scale/shear decomposition.

    Important v0.15 change:
    reflections are represented with a SIGNED scaleY instead of forcing
    scaleY positive and encoding the reflection as shearY ~= 180 degrees.

    This produces the same exact matrix, but is far more stable for animation
    interpolation, especially for SS6 parts that use Y-axis 180 degree flips.
    """
    a,b,c,d,tx,ty=[float(x) for x in M]

    sx=math.hypot(a,c)
    rot=math.degrees(math.atan2(c,a)) if sx>=1e-10 else 0.0

    det=a*d-b*c
    sy_mag=math.hypot(b,d)
    sy=sy_mag if det>=0 else -sy_mag

    if sy_mag<1e-10:
        shear_y=0.0
    else:
        actual_y_angle=math.degrees(math.atan2(d,b))
        # A negative scale reverses the Y basis direction by 180 degrees.
        basis_y_angle=actual_y_angle if sy>=0 else actual_y_angle-180.0
        shear_y=_norm_angle(basis_y_angle-rot-90.0)

    return {
        "x":tx,
        "y":ty,
        "rotation":_norm_angle(rot),
        "scaleX":sx,
        "scaleY":sy,
        "shearX":0.0,
        "shearY":shear_y,
    }

def _affine_to_spine_bone(M, name, parent="root"):
    c = _affine_to_components(M)
    out = {"name": name, "parent": parent}
    if abs(c["x"]) > 1e-8: out["x"] = round(c["x"], 6)
    if abs(c["y"]) > 1e-8: out["y"] = round(c["y"], 6)
    if abs(c["rotation"]) > 1e-8: out["rotation"] = round(c["rotation"], 6)
    if abs(c["scaleX"] - 1.0) > 1e-8: out["scaleX"] = round(c["scaleX"], 6)
    if abs(c["scaleY"] - 1.0) > 1e-8: out["scaleY"] = round(c["scaleY"], 6)
    if abs(c["shearY"]) > 1e-8: out["shearY"] = round(c["shearY"], 6)
    return out

def _affine_inv(M):
    a, b, c, d, tx, ty = [float(x) for x in M]
    det = a * d - b * c
    if abs(det) < 1e-12:
        return None
    ia = d / det
    ib = -b / det
    ic = -c / det
    idd = a / det
    itx = -(ia * tx + ib * ty)
    ity = -(ic * tx + idd * ty)
    return (ia, ib, ic, idd, itx, ity)

def _apply(M, x, y):
    a, b, c, d, tx, ty = M
    return (a * x + b * y + tx, c * x + d * y + ty)

def _parse_maps(cellmap_doc):
    if isinstance(cellmap_doc, dict) and isinstance(cellmap_doc.get("maps"), list):
        return cellmap_doc["maps"]
    raise RuntimeError("Expected cellmap.json generated by ss6runtime extract-bundle.")

def _build_regions(maps):
    counts = {}
    for m in maps:
        for c in m.get("cells", []) or []:
            base = str(c.get("plain_name") or c.get("name") or f"cell_{m.get('index',0)}_{c.get('index',0)}")
            counts[base] = counts.get(base, 0) + 1

    regions = {}
    for mi, m in enumerate(maps):
        for ci, c in enumerate(m.get("cells", []) or []):
            base = str(c.get("plain_name") or c.get("name") or f"cell_{mi}_{ci}")
            region = base if counts.get(base, 0) == 1 else f"map{mi}__{base}"
            regions[(int(m.get("index", mi)), int(c.get("index", ci)))] = (region, c, m)
    return regions

def _write_atlas(maps, texture_dir, out_dir, atlas_path):
    texture_dir = Path(texture_dir)
    out_tex = Path(out_dir) / "textures"
    out_tex.mkdir(parents=True, exist_ok=True)

    regions = _build_regions(maps)
    pages = {}
    for mi, m in enumerate(maps):
        tf = m.get("texture_file")
        if not tf:
            pngs = sorted(texture_dir.glob("*.png"))
            if mi < len(pngs):
                tf = pngs[mi].name
        if not tf:
            raise RuntimeError(f"Could not resolve texture file for cellmap {mi}")
        src = texture_dir / tf
        if not src.exists():
            raise FileNotFoundError(src)
        dst = out_tex / src.name
        if src.resolve() != dst.resolve():
            shutil.copy2(src, dst)
        with Image.open(src) as im:
            size = (im.width, im.height)
        pages[int(m.get("index", mi))] = {"file": src.name, "size": size}

    lines = []
    emitted = set()
    for mi, m in enumerate(maps):
        map_index = int(m.get("index", mi))
        page = pages[map_index]
        if map_index not in emitted:
            if lines:
                lines.append("")
            lines.extend([
                f"textures/{page['file']}",
                f"size: {page['size'][0]},{page['size'][1]}",
                "format: RGBA8888",
                "filter: Linear,Linear",
                "repeat: none",
            ])
            emitted.add(map_index)

        for ci, c in enumerate(m.get("cells", []) or []):
            key = (map_index, int(c.get("index", ci)))
            region, _, _ = regions[key]
            x = int(round(float(c.get("x", 0))))
            y = int(round(float(c.get("y", 0))))
            w = int(round(float(c.get("width", 0))))
            h = int(round(float(c.get("height", 0))))
            lines.extend([
                region,
                "  rotate: false",
                f"  xy: {x}, {y}",
                f"  size: {w}, {h}",
                f"  orig: {w}, {h}",
                "  offset: 0, 0",
                "  index: -1",
            ])
    Path(atlas_path).write_text("\n".join(lines) + "\n", encoding="utf-8")
    return regions, pages

def _uvs_from_ss6(uv_rows, flip_v=False):
    out = []
    for uv in uv_rows or []:
        if isinstance(uv, dict):
            u = float(uv.get("x", 0))
            v = float(uv.get("y", 0))
        elif isinstance(uv, (list, tuple)) and len(uv) >= 2:
            u = float(uv[0]); v = float(uv[1])
        else:
            continue
        if flip_v:
            v = 1.0 - v
        out.extend([round(u, 8), round(v, 8)])
    return out

def _rgba_hex(alpha01):
    a = max(0, min(255, round(float(alpha01) * 255)))
    return f"ffffff{a:02x}"

def _part_key_to_cell(part):
    cell = part.get("cell")
    if not isinstance(cell, dict):
        return None
    return (int(cell.get("IndexCellMap", -1)), int(cell.get("IndexCell", -1)))

def _part_visible(part, regions, show_hidden=False):
    if (not show_hidden) and bool(part.get("hidden_provisional", False)):
        return False
    return _part_key_to_cell(part) in regions

def _region_attachment_from_cell(region_name, cell):
    w = float(cell.get("width", 0))
    h = float(cell.get("height", 0))
    piv = cell.get("pivot", {}) or {}
    px = float(piv.get("x", w / 2))
    py = float(piv.get("y", h / 2))
    local_x = w / 2.0 - px
    local_y = py - h / 2.0
    att = {"path": region_name, "width": w, "height": h}
    if abs(local_x) > 1e-8:
        att["x"] = round(local_x, 6)
    if abs(local_y) > 1e-8:
        att["y"] = round(local_y, 6)
    return att

def _mesh_attachment_from_part(part, region_name, cell, mesh_v_flip=False):
    mesh = part.get("skinned_mesh")
    M = part.get("world_affine")
    if not (isinstance(mesh, dict) and mesh.get("vertices") and mesh.get("triangles") and M):
        return None, "missing mesh geometry"

    inv = _affine_inv(M)
    if inv is None:
        return None, "singular part transform"

    localverts = []
    for v in mesh["vertices"]:
        x, y = _apply(inv, float(v["x"]), float(v["y"]))
        localverts.extend([round(x, 6), round(y, 6)])

    uvs = _uvs_from_ss6(mesh.get("uv", []), mesh_v_flip)
    triangles = [int(x) for x in (mesh.get("triangles", []) or [])]
    vertex_count = len(localverts) // 2

    att = {
        "type": "mesh",
        "path": region_name,
        "uvs": uvs,
        "triangles": triangles,
        "vertices": localverts,
        "hull": vertex_count,
        "width": float(cell.get("width", 0)),
        "height": float(cell.get("height", 0)),
    }
    return att, None

def _eval_all_frames(rt):
    return [rt.evaluate_frame(i, "native2d", "zxy") for i in range(int(rt.frame_count))]

def _build_static_setup(frames, maps, regions, frame0_index=0, mesh_v_flip=False, show_hidden=False):
    state0 = frames[frame0_index]
    parts0 = state0["parts"]
    bones = [{"name": "root"}]
    slots = []
    attachments = {}
    slot_order = []
    part_to_slot = {}
    slot_meta = {}
    warnings = []
    region_count = 0
    mesh_count = 0

    for p in parts0:
        M = p.get("world_affine")
        if M:
            bones.append(_affine_to_spine_bone(M, str(p["name"]), "root"))

    drawable = []
    for p in parts0:
        key = _part_key_to_cell(p)
        if key is None or key not in regions:
            continue
        if (not show_hidden) and bool(p.get("hidden_provisional", False)):
            continue
        drawable.append(p)
    drawable.sort(key=lambda p: (int(p.get("priority", 0) or 0), int(p.get("index", 0))))

    # Gather every attachment actually used by each slot across all frames.
    used_cells = {}
    for state in frames:
        by_index = {int(pp["index"]): pp for pp in state["parts"]}
        for p0 in drawable:
            idx = int(p0["index"])
            p = by_index.get(idx)
            if not p:
                continue
            key = _part_key_to_cell(p)
            if key is None or key not in regions:
                continue
            used_cells.setdefault(idx, [])
            if key not in used_cells[idx]:
                used_cells[idx].append(key)

    for p in drawable:
        idx = int(p["index"])
        pname = str(p["name"])
        slot_name = pname
        part_to_slot[idx] = slot_name
        slot_order.append(slot_name)

        key0 = _part_key_to_cell(p)
        region_name0, cell0, _ = regions[key0]

        slots.append({"name": slot_name, "bone": pname, "attachment": slot_name})
        opacity = p.get("opacity", 1.0)
        if isinstance(opacity, (int, float)) and float(opacity) < 0.9999:
            slots[-1]["color"] = _rgba_hex(opacity)

        attachments[slot_name] = {}
        attach_names = {}

        keys_for_slot = used_cells.get(idx, [key0])
        for j, key in enumerate(keys_for_slot):
            region_name, cell, _map = regions[key]
            attach_name = slot_name if key == key0 else f"{slot_name}__{region_name}"
            frame_part = None
            for state in frames:
                by_index = {int(pp["index"]): pp for pp in state["parts"]}
                pp = by_index.get(idx)
                if pp and _part_key_to_cell(pp) == key:
                    frame_part = pp
                    break

            if frame_part and isinstance(frame_part.get("skinned_mesh"), dict) and frame_part["skinned_mesh"].get("vertices"):
                att, err = _mesh_attachment_from_part(frame_part, region_name, cell, mesh_v_flip=mesh_v_flip)
                if att is not None:
                    attachments[slot_name][attach_name] = att
                    mesh_count += 1
                else:
                    warnings.append(f"{slot_name}: mesh attachment fallback to region for {attach_name} ({err})")
                    attachments[slot_name][attach_name] = _region_attachment_from_cell(region_name, cell)
                    region_count += 1
            else:
                attachments[slot_name][attach_name] = _region_attachment_from_cell(region_name, cell)
                region_count += 1
            attach_names[key] = attach_name

        slot_meta[slot_name] = {
            "part_index": idx,
            "setup_cell_key": key0,
            "attachment_names": attach_names,
            "setup_attachment": slot_name,
            "setup_is_mesh": slot_name in attachments and isinstance(attachments[slot_name].get(slot_name), dict) and attachments[slot_name][slot_name].get("type") == "mesh"
        }

    return {
        "bones": bones,
        "slots": slots,
        "attachments": attachments,
        "slot_order": slot_order,
        "part_to_slot": part_to_slot,
        "slot_meta": slot_meta,
        "warnings": warnings,
        "region_attachments": region_count,
        "mesh_attachments": mesh_count,
    }

def _timeline_changed(prev, cur, tol=1e-8):
    if prev is None:
        return True
    if isinstance(cur, dict):
        keys = set(prev.keys()) | set(cur.keys())
        for k in keys:
            pv = prev.get(k)
            cv = cur.get(k)
            if isinstance(cv, (int, float)) or isinstance(pv, (int, float)):
                if abs(float(pv or 0.0) - float(cv or 0.0)) > tol:
                    return True
            else:
                if pv != cv:
                    return True
        return False
    return prev != cur


def _unwrap_delta(value, reference, previous_delta=None):
    """Return value-reference, choosing the 360-degree equivalent nearest previous_delta."""
    d=float(value)-float(reference)
    while d > 180.0:
        d -= 360.0
    while d <= -180.0:
        d += 360.0
    if previous_delta is not None:
        while d - previous_delta > 180.0:
            d -= 360.0
        while d - previous_delta < -180.0:
            d += 360.0
    return d

def _setup_components_by_bone(setup_data):
    out={}
    for b in setup_data["bones"]:
        if b["name"]=="root":
            continue
        out[b["name"]]={
            "x":float(b.get("x",0.0)),
            "y":float(b.get("y",0.0)),
            "rotation":float(b.get("rotation",0.0)),
            "scaleX":float(b.get("scaleX",1.0)),
            "scaleY":float(b.get("scaleY",1.0)),
            "shearX":float(b.get("shearX",0.0)),
            "shearY":float(b.get("shearY",0.0)),
        }
    return out


def _build_deform_data(rt, frames, regions, setup_data):
    """
    Build Spine deform timelines for the unweighted mesh attachments emitted by this exporter.

    The setup mesh stores local x,y vertices. At each frame:
      runtime skinned world vertices
        -> inverse(current flat bone world affine)
        -> current mesh vertices in Spine bone-local space
        -> subtract setup mesh vertices
        -> Spine deform delta

    JSON shape:
      deform -> default -> slot -> attachment -> [keyframes]
    """
    fps=float(max(rt.fps,1.0))
    deform_skin={}
    warnings=[]
    timeline_count=0
    keyframe_count=0

    for slot_name, meta in setup_data["slot_meta"].items():
        idx=int(meta["part_index"])
        slot_atts=setup_data["attachments"].get(slot_name,{})
        if not slot_atts:
            continue

        for cell_key, attach_name in meta["attachment_names"].items():
            setup_att=slot_atts.get(attach_name)
            if not isinstance(setup_att,dict) or setup_att.get("type")!="mesh":
                continue

            setup_vertices=setup_att.get("vertices",[]) or []
            if len(setup_vertices)%2!=0 or not setup_vertices:
                warnings.append(f"{slot_name}/{attach_name}: invalid setup mesh vertices")
                continue
            vertex_count=len(setup_vertices)//2

            keys=[]
            prev_delta=None

            for fi,state in enumerate(frames):
                by_index={int(p["index"]):p for p in state["parts"]}
                p=by_index.get(idx)
                if not p or _part_key_to_cell(p)!=cell_key:
                    continue

                mesh=p.get("skinned_mesh")
                M=p.get("world_affine")
                if not (isinstance(mesh,dict) and mesh.get("vertices") and M):
                    continue
                verts=mesh["vertices"]
                if len(verts)!=vertex_count:
                    warnings.append(
                        f"{slot_name}/{attach_name}: frame {fi} vertex count {len(verts)} != setup {vertex_count}"
                    )
                    continue

                inv=_affine_inv(M)
                if inv is None:
                    warnings.append(f"{slot_name}/{attach_name}: frame {fi} singular bone matrix")
                    continue

                delta=[]
                for vi,v in enumerate(verts):
                    lx,ly=_apply(inv,float(v["x"]),float(v["y"]))
                    dx=lx-float(setup_vertices[2*vi])
                    dy=ly-float(setup_vertices[2*vi+1])
                    # suppress tiny floating-point noise
                    if abs(dx)<1e-6: dx=0.0
                    if abs(dy)<1e-6: dy=0.0
                    delta.extend([round(dx,6),round(dy,6)])

                # Always retain per-frame keys while the attachment is active.
                # This matches the runtime's already-sampled frame states.
                key={"time":_frame_time(fi,fps)}
                if any(abs(v)>1e-8 for v in delta):
                    key["vertices"]=delta
                keys.append(key)
                keyframe_count+=1
                prev_delta=delta

            if keys:
                deform_skin.setdefault(slot_name,{})[attach_name]=keys
                timeline_count+=1

    return ({"default":deform_skin} if deform_skin else {}), warnings, timeline_count, keyframe_count


def _all_close(vals, default, tol=1e-6):
    return all(abs(float(v)-float(default))<=tol for v in vals)

def _key_values(k, fields):
    return tuple(float(k.get(f,0.0)) for f in fields)

def _simplify_linear_keys(keys, fields, tol=1e-5):
    """
    Remove middle samples that lie on the straight line between their neighbors.
    This preserves the same linear interpolation while greatly reducing dense
    per-frame sampled SS6 timelines.
    """
    if len(keys)<=2:
        return keys
    out=[keys[0]]
    for i in range(1,len(keys)-1):
        a=out[-1]
        b=keys[i]
        c=keys[i+1]
        ta=float(a.get("time",0)); tb=float(b.get("time",0)); tc=float(c.get("time",0))
        if tc-ta<=1e-12:
            out.append(b); continue
        r=(tb-ta)/(tc-ta)
        av=_key_values(a,fields); bv=_key_values(b,fields); cv=_key_values(c,fields)
        predicted=tuple(x+r*(z-x) for x,z in zip(av,cv))
        if any(abs(y-p)>tol for y,p in zip(bv,predicted)):
            out.append(b)
    out.append(keys[-1])
    return out

def _matrix_from_components(c):
    rot=math.radians(float(c["rotation"]))
    ay=math.radians(float(c["rotation"])+90.0+float(c["shearY"]))
    sx=float(c["scaleX"]); sy=float(c["scaleY"])
    return (
        math.cos(rot)*sx,
        math.cos(ay)*sy,
        math.sin(rot)*sx,
        math.sin(ay)*sy,
        float(c["x"]),
        float(c["y"])
    )

def _selfcheck_flat_bones(frames, setup_data):
    """
    Verify that our setup + relative animation channels reconstruct the Python
    runtime world affine matrices at frame samples.
    """
    setup=_setup_components_by_bone(setup_data)
    max_err=0.0
    worst=None
    for fi,state in enumerate(frames):
        by_name={str(p["name"]):p for p in state["parts"]}
        for bn,base in setup.items():
            p=by_name.get(bn)
            if not p or not p.get("world_affine"): continue
            cur=_affine_to_components(p["world_affine"])
            # Relative timeline semantics at an exact sample.
            comp={
                "x":base["x"]+(cur["x"]-base["x"]),
                "y":base["y"]+(cur["y"]-base["y"]),
                "rotation":base["rotation"]+_unwrap_delta(cur["rotation"],base["rotation"]),
                "scaleX":base["scaleX"]*((cur["scaleX"]/base["scaleX"]) if abs(base["scaleX"])>1e-12 else 1.0),
                "scaleY":base["scaleY"]*((cur["scaleY"]/base["scaleY"]) if abs(base["scaleY"])>1e-12 else 1.0),
                "shearY":base["shearY"]+_unwrap_delta(cur["shearY"],base["shearY"]),
            }
            R=_matrix_from_components(comp)
            M=p["world_affine"]
            e=max(abs(float(a)-float(b)) for a,b in zip(M,R))
            if e>max_err:
                max_err=e;worst={"frame":fi,"bone":bn,"error":e}
    return {"max_matrix_error":max_err,"worst":worst}

def _build_animation_data(rt, frames, regions, setup_data, show_hidden=False):
    """
    Spine bone animation keys are RELATIVE TO THE SETUP POSE.

    translate: frame_position - setup_position
    rotate:    frame_rotation - setup_rotation
    scale:     frame_scale / setup_scale
    shear:     frame_shear - setup_shear

    The previous v0.12 exporter incorrectly wrote absolute evaluated values here.
    """
    fps=float(max(rt.fps,1.0))
    anim_name=str(frames[0].get("animation") or "anim_0")
    setup_comp=_setup_components_by_bone(setup_data)
    bone_names=list(setup_comp.keys())

    bones_tl={bn:{"translate":[],"rotate":[],"scale":[],"shear":[]} for bn in bone_names}
    slots_tl={}
    setup_order=list(setup_data["slot_order"])
    draworder_changes=[]
    warnings=[]

    prev_draw=list(setup_order)
    current_attachment_by_slot={s["name"]:s.get("attachment") for s in setup_data["slots"]}
    setup_slot_color={s["name"]:s.get("color","ffffffff") for s in setup_data["slots"]}
    prev_slot_state={
        s["name"]:{
            "attachment":s.get("attachment"),
            "color":s.get("color","ffffffff")
        } for s in setup_data["slots"]
    }
    prev_rot_delta={bn:None for bn in bone_names}
    prev_shear_delta={bn:None for bn in bone_names}

    # Cache part lookup by name for each frame.
    frame_by_name=[]
    for state in frames:
        frame_by_name.append({str(p["name"]):p for p in state["parts"]})

    for fi,state in enumerate(frames):
        t=_frame_time(fi,fps)
        by_name=frame_by_name[fi]

        # Bone timelines, relative to setup pose.
        for bn in bone_names:
            p=by_name.get(bn)
            if not p or not p.get("world_affine"):
                continue

            cur=_affine_to_components(p["world_affine"])
            base=setup_comp[bn]

            tx=cur["x"]-base["x"]
            ty=cur["y"]-base["y"]

            rd=_unwrap_delta(cur["rotation"],base["rotation"],prev_rot_delta[bn])
            prev_rot_delta[bn]=rd

            sx_base=base["scaleX"]
            sy_base=base["scaleY"]
            sx=(cur["scaleX"]/sx_base) if abs(sx_base)>1e-12 else 1.0
            sy=(cur["scaleY"]/sy_base) if abs(sy_base)>1e-12 else 1.0

            shy=_unwrap_delta(cur["shearY"],base["shearY"],prev_shear_delta[bn])
            prev_shear_delta[bn]=shy

            bones_tl[bn]["translate"].append({
                "time":t,
                "x":round(tx,6),
                "y":round(ty,6)
            })
            bones_tl[bn]["rotate"].append({
                "time":t,
                "angle":round(rd,6)
            })
            bones_tl[bn]["scale"].append({
                "time":t,
                "x":round(sx,6),
                "y":round(sy,6)
            })
            bones_tl[bn]["shear"].append({
                "time":t,
                "x":0.0,
                "y":round(shy,6)
            })

        # Slots.
        current_order_parts=[]
        by_index={int(p["index"]):p for p in state["parts"]}
        for idx,slot_name in setup_data["part_to_slot"].items():
            p=by_index.get(int(idx))
            if not p:
                continue

            key=_part_key_to_cell(p)
            visible=_part_visible(p,regions,show_hidden=show_hidden)
            meta=setup_data["slot_meta"][slot_name]
            attach_name=meta["attachment_names"].get(key,current_attachment_by_slot.get(slot_name))
            alpha=0.0 if not visible else float(
                p.get("opacity",1.0) if isinstance(p.get("opacity",1.0),(int,float)) else 1.0
            )

            cur_state={"attachment":attach_name,"color":_rgba_hex(alpha)}
            prev=prev_slot_state.get(slot_name)
            if slot_name not in slots_tl:
                slots_tl[slot_name]={}

            if prev is None or prev.get("attachment")!=cur_state["attachment"]:
                keyframe={"time":t}
                if cur_state["attachment"] is not None:
                    keyframe["name"]=cur_state["attachment"]
                slots_tl[slot_name].setdefault("attachment",[]).append(keyframe)
                current_attachment_by_slot[slot_name]=cur_state["attachment"]

            if prev is None or prev.get("color")!=cur_state["color"]:
                slots_tl[slot_name].setdefault("color",[]).append({
                    "time":t,
                    "color":cur_state["color"]
                })

            prev_slot_state[slot_name]=cur_state
            current_order_parts.append((
                int(p.get("priority",0) or 0),
                int(p.get("index",0)),
                slot_name
            ))

        # Dynamic draw order.
        current_order=[sn for _,_,sn in sorted(current_order_parts)]
        if current_order and current_order!=prev_draw:
            if fi>0:
                offsets=[]
                # Spine offsets are relative to setup order.
                for current_i,slot_name in enumerate(current_order):
                    if slot_name not in setup_order:
                        continue
                    setup_i=setup_order.index(slot_name)
                    off=current_i-setup_i
                    if off!=0:
                        offsets.append({"slot":slot_name,"offset":off})
                if offsets:
                    draworder_changes.append({"time":t,"offsets":offsets})
            prev_draw=current_order

    # v0.15: omit channels that are identical to setup for the entire clip,
    # and remove redundant linear samples from channels that do change.
    bones_block={}
    for bn,tl in bones_tl.items():
        item={}

        if tl["translate"]:
            xs=[k["x"] for k in tl["translate"]]; ys=[k["y"] for k in tl["translate"]]
            if not (_all_close(xs,0.0) and _all_close(ys,0.0)):
                item["translate"]=_simplify_linear_keys(tl["translate"],("x","y"))

        if tl["rotate"]:
            vals=[k["angle"] for k in tl["rotate"]]
            if not _all_close(vals,0.0):
                item["rotate"]=_simplify_linear_keys(tl["rotate"],("angle",))

        if tl["scale"]:
            xs=[k["x"] for k in tl["scale"]]; ys=[k["y"] for k in tl["scale"]]
            if not (_all_close(xs,1.0) and _all_close(ys,1.0)):
                item["scale"]=_simplify_linear_keys(tl["scale"],("x","y"))

        if tl["shear"]:
            xs=[k["x"] for k in tl["shear"]]; ys=[k["y"] for k in tl["shear"]]
            if not (_all_close(xs,0.0) and _all_close(ys,0.0)):
                item["shear"]=_simplify_linear_keys(tl["shear"],("x","y"))

        if item:
            bones_block[bn]=item

    slots_block={}
    for sn,tl in slots_tl.items():
        item={}
        for k in ("attachment","color"):
            if tl.get(k):
                item[k]=tl[k]
        if item:
            slots_block[sn]=item

    anim={"bones":bones_block}
    if slots_block:
        anim["slots"]=slots_block
    if draworder_changes:
        anim["draworder"]=draworder_changes

    deform_block,deform_warnings,deform_timeline_count,deform_keyframe_count=_build_deform_data(
        rt,frames,regions,setup_data
    )
    if deform_block:
        anim["deform"]=deform_block
    warnings.extend(deform_warnings)

    return anim_name,anim,warnings,deform_timeline_count,deform_keyframe_count

