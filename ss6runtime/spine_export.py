def _load_runtime_set(parts_raw_path, animation_entries):
    """
    animation_entries: list of {"name","animation_raw",...}
    Returns [(entry, Runtime, frames), ...]
    """
    out=[]
    for e in animation_entries:
        rt=Runtime.from_files(parts_raw_path,e["animation_raw"])
        frames=_eval_all_frames(rt)
        out.append((e,rt,frames))
    return out

def _select_setup_animation(runtime_set, setup_animation_name=None):
    if setup_animation_name:
        for i,(e,rt,frames) in enumerate(runtime_set):
            if str(e["name"])==str(setup_animation_name):
                return i
        raise RuntimeError(
            f"Setup animation not found: {setup_animation_name}. "
            f"Available: {[x[0]['name'] for x in runtime_set]}"
        )

    # Prefer a stable idle/stand animation when available.
    preferred=("mot_stand","stand","idle","mot_ready","ready","mot_action_01")
    for target in preferred:
        for i,(e,rt,frames) in enumerate(runtime_set):
            if str(e["name"]).lower()==target:
                return i
    return 0

def _filter_animation_entries(entries, include=None, exclude=None):
    inc=re.compile(include,re.I) if include else None
    exc=re.compile(exclude,re.I) if exclude else None
    out=[]
    for e in entries:
        name=str(e["name"])
        if inc and not inc.search(name):
            continue
        if exc and exc.search(name):
            continue
        out.append(e)
    return out

