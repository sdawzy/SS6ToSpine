def export_spine_frame_swap(parts_raw_path,animation_raw_path,cellmap_path,texture_dir,
                            output_dir,setup_frame=0,name=None,mesh_v_flip=False,
                            show_hidden=False,dedupe=True):
    """
    Maximum-compatibility animation exporter.

    No animated bones.
    No deform timelines.

    Each visible SS6 part gets one Spine slot on the root bone. For every frame,
    the evaluated final geometry is baked into a mesh attachment. The animation
    is reproduced by a stepped attachment timeline that switches to the correct
    baked mesh each frame.

    This is intentionally data-heavy but provides a very strong fidelity baseline.
    """
    out=Path(output_dir)
    out.mkdir(parents=True,exist_ok=True)

    rt=Runtime.from_files(parts_raw_path,animation_raw_path)
    frames=_eval_all_frames(rt)
    maps=_parse_maps(_load(cellmap_path))
    regions=_build_regions(maps)

    skeleton_name=_safe(name or Path(output_dir).name or "ss6_character")
    atlas_path=out/f"{skeleton_name}.atlas"
    _write_atlas(maps,texture_dir,out,atlas_path)

    fps=float(max(rt.fps,1.0))
    anim_name=str(frames[0].get("animation") or "animation")

    # All parts that ever reference a known cell.
    visual_indices=[]
    part_names={}
    for state in frames:
        for p in state["parts"]:
            idx=int(p["index"])
            key=_part_key_to_cell(p)
            if key is None or key not in regions:
                continue
            if idx not in visual_indices:
                visual_indices.append(idx)
            part_names[idx]=str(p["name"])

    # Use setup frame priority for base slot order.
    sf=frames[int(setup_frame)]
    sf_byidx={int(p["index"]):p for p in sf["parts"]}
    visual_indices.sort(key=lambda idx:(
        int(sf_byidx.get(idx,{}).get("priority",0) or 0),
        idx
    ))

    bones=[{"name":"root"}]
    slots=[]
    skin_attachments={}
    slot_timelines={}
    geometry_cache={}
    frame_attachment_name={}
    warnings=[]
    total_attachments=0

    def geom_signature(cell_key,verts,uvs,tris):
        if not dedupe:
            return None
        # Rounded signature so identical sampled geometry can reuse attachment.
        return (
            tuple(cell_key),
            tuple(round(float(x),5) for x in verts),
            tuple(round(float(x),6) for x in uvs),
            tuple(int(x) for x in tris)
        )

    # First create all frame-specific geometry attachments.
    for idx in visual_indices:
        slot_name=part_names[idx]
        skin_attachments[slot_name]={}
        cache_for_slot={}
        previous_attachment=None

        for fi,state in enumerate(frames):
            byidx={int(p["index"]):p for p in state["parts"]}
            p=byidx.get(idx)
            if p is None:
                frame_attachment_name[(idx,fi)]=None
                continue

            cell_key=_part_key_to_cell(p)
            visible=_part_visible(p,regions,show_hidden=show_hidden)
            if cell_key is None or cell_key not in regions or not visible:
                frame_attachment_name[(idx,fi)]=None
                continue

            region_name,cell,_=regions[cell_key]
            verts,uvs,tris=_part_world_geometry(p,cell,mesh_v_flip=mesh_v_flip)
            if not verts:
                frame_attachment_name[(idx,fi)]=None
                warnings.append(f"{slot_name}: frame {fi} geometry missing")
                continue

            sig=geom_signature(cell_key,verts,uvs,tris)
            if sig is not None and sig in cache_for_slot:
                aname=cache_for_slot[sig]
            else:
                aname=f"{slot_name}__f{fi:03d}"
                # Ensure uniqueness if same name somehow already used.
                suffix=1
                base=aname
                while aname in skin_attachments[slot_name]:
                    aname=f"{base}_{suffix}"
                    suffix+=1

                skin_attachments[slot_name][aname]={
                    "type":"mesh",
                    "path":region_name,
                    "uvs":uvs,
                    "triangles":tris,
                    "vertices":verts,
                    "hull":len(verts)//2,
                    "width":float(cell.get("width",0)),
                    "height":float(cell.get("height",0)),
                }
                total_attachments+=1
                if sig is not None:
                    cache_for_slot[sig]=aname

            frame_attachment_name[(idx,fi)]=aname

        # Setup attachment: selected frame if visible, otherwise first visible frame.
        setup_attachment=frame_attachment_name.get((idx,int(setup_frame)))
        if setup_attachment is None:
            for fi in range(len(frames)):
                q=frame_attachment_name.get((idx,fi))
                if q is not None:
                    setup_attachment=q
                    break

        slot={"name":slot_name,"bone":"root"}
        if setup_attachment is not None:
            slot["attachment"]=setup_attachment

        p0=sf_byidx.get(idx)
        visible0=False
        alpha0=1.0
        if p0 is not None:
            visible0=_part_visible(p0,regions,show_hidden=show_hidden)
            alpha0=float(p0.get("opacity",1.0) if isinstance(p0.get("opacity",1.0),(int,float)) else 1.0)
        if not visible0:
            alpha0=0.0
        if alpha0<0.9999:
            slot["color"]=_rgba_hex(alpha0)
        slots.append(slot)

        # Build stepped attachment timeline. Include frame 0 explicitly so the
        # animation is self-contained even if setup_frame != 0.
        keys=[]
        prev_marker=object()
        prev=None
        for fi in range(len(frames)):
            aname=frame_attachment_name.get((idx,fi))
            # None means hide attachment.
            if fi==0 or aname!=prev:
                key={"time":_frame_time(fi,fps),"curve":"stepped"}
                if aname is not None:
                    key["name"]=aname
                keys.append(key)
                prev=aname
        if keys:
            slot_timelines.setdefault(slot_name,{})["attachment"]=keys

        # Opacity / hidden timeline.
        color_keys=[]
        prev_color=None
        for fi,state in enumerate(frames):
            byidx={int(p["index"]):p for p in state["parts"]}
            p=byidx.get(idx)
            if p is None:
                color="ffffff00"
            else:
                visible=_part_visible(p,regions,show_hidden=show_hidden)
                alpha=float(p.get("opacity",1.0) if isinstance(p.get("opacity",1.0),(int,float)) else 1.0) if visible else 0.0
                color=_rgba_hex(alpha)
            if fi==0 or color!=prev_color:
                color_keys.append({
                    "time":_frame_time(fi,fps),
                    "color":color,
                    "curve":"stepped"
                })
                prev_color=color
        # Avoid redundant constant-opaque timeline.
        if not (len(color_keys)==1 and color_keys[0]["color"]=="ffffffff"):
            slot_timelines.setdefault(slot_name,{})["color"]=color_keys

    # Draw order sampled per frame.
    setup_order=[s["name"] for s in slots]
    draworder=[]
    prev_order=setup_order
    for fi,state in enumerate(frames):
        rows=[]
        for p in state["parts"]:
            idx=int(p["index"])
            if idx not in visual_indices:
                continue
            rows.append((int(p.get("priority",0) or 0),idx,part_names[idx]))
        cur=[s for _,_,s in sorted(rows)]
        if fi>0 and cur and cur!=prev_order:
            offsets=[]
            # Spine offsets are against setup slot order.
            for ci,slot_name in enumerate(cur):
                if slot_name not in setup_order:
                    continue
                si=setup_order.index(slot_name)
                off=ci-si
                if off!=0:
                    offsets.append({"slot":slot_name,"offset":off})
            if offsets:
                draworder.append({
                    "time":_frame_time(fi,fps),
                    "offsets":offsets
                })
            prev_order=cur

    animation={"slots":slot_timelines}
    if draworder:
        animation["draworder"]=draworder

    doc={
        "skeleton":{
            "spine":"4.2.00",
            "images":"./textures/",
            "ss6Runtime":"ss6python_runtime_v22",
            "ss6Animation":anim_name,
            "ss6Frame":int(setup_frame),
            "ss6Mode":"frame-swap-baked-mesh"
        },
        "bones":bones,
        "slots":slots,
        "skins":[{"name":"default","attachments":skin_attachments}],
        "animations":{
            "setup":{"bones":{"root":{"rotate":[{"time":0.0,"angle":0.0}]}}},
            anim_name:animation
        }
    }

    json_path=out/f"{skeleton_name}.json"
    json_path.write_text(json.dumps(doc,ensure_ascii=False,indent=2),encoding="utf-8")

    attachment_timeline_count=sum(
        1 for v in slot_timelines.values() if "attachment" in v
    )
    attachment_keyframes=sum(
        len(v.get("attachment",[])) for v in slot_timelines.values()
    )
    color_timeline_count=sum(
        1 for v in slot_timelines.values() if "color" in v
    )
    color_keyframes=sum(
        len(v.get("color",[])) for v in slot_timelines.values()
    )

    report={
        "json":str(json_path),
        "atlas":str(atlas_path),
        "animation":anim_name,
        "frame_count":int(rt.frame_count),
        "fps":float(rt.fps),
        "export_mode":"frame-swap-baked-mesh",
        "bones":1,
        "slots":len(slots),
        "mesh_attachments":total_attachments,
        "attachment_timelines":attachment_timeline_count,
        "attachment_keyframes":attachment_keyframes,
        "color_timelines":color_timeline_count,
        "color_keyframes":color_keyframes,
        "draworder_keyframes":len(draworder),
        "deform_timelines":0,
        "dedupe":bool(dedupe),
        "warnings":warnings,
    }
    (out/"spine_export_report.json").write_text(
        json.dumps(report,ensure_ascii=False,indent=2),
        encoding="utf-8"
    )
    return report

